// Builds the browser engine (src/client.js -> dist/core.js) and the text modules the Worker serves:
// dist/core-text.js (the engine, with a version from its hash, so its URL changes with each build) and
// dist/example-text.js (backend/mock/mock_market_scan.json, the example payload). Run by
// `npm run build`, which wrangler runs before every deploy and `npm test` before testing.
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { build } from 'esbuild';

const res = await build({ entryPoints: ['src/client.js'], bundle: true, format: 'esm', platform: 'browser', target: 'es2022',
  minify: true, write: false, legalComments: 'none', logLevel: 'warning' });
const code = res.outputFiles[0].text;
const version = createHash('sha256').update(code).digest('hex').slice(0, 12);
mkdirSync('dist', { recursive: true });
writeFileSync('dist/core.js', code);
writeFileSync('dist/core-text.js', `// Generated by scripts/build-client.mjs from src/client.js: don't edit.\n`
  + `export const CORE_VERSION = ${JSON.stringify(version)};\nexport const CORE = ${JSON.stringify(code)};\n`);
const example = JSON.stringify(JSON.parse(readFileSync('../../backend/mock/mock_market_scan.json', 'utf8')));
writeFileSync('dist/example-text.js', `// Generated by scripts/build-client.mjs from backend/mock/mock_market_scan.json: don't edit.\n`
  + `export default ${JSON.stringify(example)};\n`);
console.log(`dist/core.js ${(code.length / 1024).toFixed(0)} KiB (version ${version}), example ${(example.length / 1024).toFixed(0)} KiB`);
